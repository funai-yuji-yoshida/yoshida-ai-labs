// 正規化された文字列に対して、表記ゆれを考慮して一致判定
export function matchWithVariants(
  normalizedAnswer: string,
  normalizedWord: string
): boolean {
  // 完全一致
  if (normalizedAnswer === normalizedWord) {
    return true;
  }

  // 表記ゆれ辞書をチェック
  for (const [canonical, variants] of Object.entries(wordVariants)) {
    const normalizedVariants = variants.map((v) => normalizeForVariants(v));

    // 回答と単語が両方とも同じ正規形の表記ゆれに含まれるか
    if (
      normalizedVariants.includes(normalizedAnswer) &&
      normalizedVariants.includes(normalizedWord)
    ) {
      return true;
    }
  }

  return false;
}

// 表記ゆれ判定用の正規化（より緩い正規化）
function normalizeForVariants(text: string): string {
  return text
    .trim()
    .replace(/\s+/g, "")
    .toLowerCase()
    .replace(/[ぁ-ん]/g, (char) => {
      // ひらがなをカタカナに変換
      return String.fromCharCode(char.charCodeAt(0) + 0x60);
    })
    .replace(/[Ａ-Ｚａ-ｚ０-９]/g, (char) => {
      // 全角英数字を半角に変換
      return String.fromCharCode(char.charCodeAt(0) - 0xfee0);
    })
    .replace(/ー/g, "") // 長音記号を削除
    .replace(/゛/g, "") // 濁点を削除（一部の特殊ケース用）
    .replace(/゜/g, ""); // 半濁点を削除
}
